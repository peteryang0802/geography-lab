import { createHash } from 'node:crypto';
import { readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { topicViews } from '../src/topic-views.js';
import { profileCourseTasks } from '../src/profile-assessment.js';

const require = createRequire(import.meta.url);
const { build } = require(resolve(dirname(realpathSync(process.argv[2])), '..'));
const options = { bundle: true, platform: 'browser', target: 'es2022', minify: true };
const volumeIds = ['7b', '8a', '8b'];
const volumeIndex = Object.fromEntries(await Promise.all(volumeIds.map(async id => {
  const {default: book} = await import(`../src/term-${id}.js`);
  return [id, book.chapters.map(chapter => ({title: chapter.title, lessons: chapter.lessons.map(lesson => ({
    id: lesson.id, title: lesson.title, page: lesson.page, project: Boolean(lesson.project),
    optionCount: lesson.review.options.length, answer: lesson.review.answer,
    checks: profileCourseTasks(lesson).map(task => ({ id: task.id, prompt: task.prompt, answer: task.answer, optionCount: task.options.length })),
  }))}))];
})));

await build({
  ...options,
  entryPoints: ['src/app.js'],
  outfile: 'src/app-runtime.js',
  define: { GEOLAB_VOLUME_INDEX: JSON.stringify(volumeIndex) },
  format: 'esm',
  banner: { js: '/* Generated by scripts/build-app.sh. Edit src/app.js and its modules. */' },
  plugins: [{
    name: 'keep-activities-on-demand',
    setup(buildTask) {
      buildTask.onResolve({ filter: /^\./ }, args => {
        if (args.kind === 'dynamic-import') return { path: args.path, external: true };
      });
    },
  }],
});

const galleries = Object.fromEntries(Object.entries(topicViews).map(([id, topic]) => [
  id, topic.photos.map(({ file, mobileFile }) => ({ file, mobileFile })),
]));
const labEntry = 'src/lab-ui.js';
const { metafile: lab } = await build({
  ...options, entryPoints: [labEntry], format: 'esm', metafile: true, write: false,
});
const labDependencies = Object.keys(lab.inputs).filter(input => input !== labEntry);
const { outputFiles: [startup] } = await build({
  ...options,
  entryPoints: ['src/startup-media.js'],
  format: 'iife',
  define: {
    EARLY_GALLERY_PHOTOS: JSON.stringify(galleries),
    EARLY_LAB_DEPENDENCIES: JSON.stringify(labDependencies),
  },
  write: false,
});
const hash = createHash('sha256').update(readFileSync('src/app-runtime.js')).digest('hex').slice(0, 10);
const html = readFileSync('index.html', 'utf8')
  .replace(/<!-- startup-media -->[\s\S]*?<!-- \/startup-media -->/,
    () => `<!-- startup-media --><script>${startup.text.trim()}</script><!-- /startup-media -->`)
  .replace(/src\/app-runtime\.js(?:\?v=[a-z0-9]+)?/, `src/app-runtime.js?v=${hash}`);
writeFileSync('index.html', html);
