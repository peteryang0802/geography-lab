function task(table, prefix, id) {
  if (!Object.hasOwn(table, id)) return null;
  const [prompt, evidence, answer, options] = table[id];
  return { id: prefix + id, prompt, evidence, answer,
    options: options.map(([label, feedback]) => ({ label, feedback })) };
}

